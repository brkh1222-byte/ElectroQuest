export type Lang = "mn" | "en";
const DICTS: Record<Lang, Record<StringKey, string>> = { mn, en };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: StringKey) => string;
  tr: (l: L) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("mn");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("lang");
      // eslint-disable-next-line react-hooks/set-state-in-effect -- read the saved language once after hydration
      if (saved === "en" || saved === "mn") setLangState(saved);
    } catch {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("lang", l);
    } catch {}
  }, []);
  const t = useCallback((k: StringKey) => DICTS[lang][k], [lang]);
  const tr = useCallback((l: L) => l[lang], [lang]);
  return <Ctx.Provider value={{ lang, setLang, t, tr }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n outside LangProvider");
  return c;
}
